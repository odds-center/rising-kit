import AppKit
import Carbon.HIToolbox
import RisingKitCore

/// 복사한 글·파일·이미지를 기록해 두었다가 다시 붙여 넣게 해 준다.
/// 기록은 이 맥의 사용자 폴더에만 저장하고(본인만 읽을 수 있는 권한), 최근 200개·7일까지만 둔다.
final class ClipboardMonitor {
    static let shared = ClipboardMonitor()

    private(set) var history = ClipHistory()
    private var changeCount = NSPasteboard.general.changeCount
    private var timer: Timer?

    private static let folder: URL = FileManager.default
        .urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
        .appendingPathComponent("RisingKit/clipboard", isDirectory: true)
    private static let historyFile = folder.appendingPathComponent("history.json")

    /// 비밀번호 관리자 등, 여기서 복사한 것은 기록하지 않는다.
    private static let excludedApps: Set<String> = [
        "com.bitwarden.desktop", "com.1password.1password", "com.agilebits.onepassword7",
        "com.apple.keychainaccess", "com.apple.Passwords", "com.lastpass.LastPass", "org.keepassxc.keepassxc",
    ]
    /// 앱이 "이건 비밀이니 기록하지 말라"고 표시할 때 쓰는 클립보드 종류 (nspasteboard.org 규약)
    private static let secretTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]
    private static let maxImageBytes = 8 * 1024 * 1024

    var enabled: Bool { ConfigStore.shared.config.clipboardHistory }

    func start() {
        load()
        deleteImages(of: history.prune(now: Date()))
        save()
        timer = Timer.scheduledTimer(withTimeInterval: 0.6, repeats: true) { [weak self] _ in self?.check() }
    }

    private func check() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != changeCount else { return }
        changeCount = pasteboard.changeCount
        guard enabled else { return }

        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        if !types.isDisjoint(with: Self.secretTypes) { return }
        if let front = NSWorkspace.shared.frontmostApplication?.bundleIdentifier, Self.excludedApps.contains(front) {
            return
        }

        let id = UUID().uuidString
        let item: ClipItem
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            item = ClipItem(id: id, kind: .file, text: urls.map(\.path).joined(separator: "\n"), date: Date())
        } else if let text = pasteboard.string(forType: .string) {
            item = ClipItem(id: id, kind: .text, text: text, date: Date())
        } else if let data = pasteboard.data(forType: .png) ?? pasteboard.data(forType: .tiff),
                  let rep = NSBitmapImageRep(data: data),
                  let png = rep.representation(using: .png, properties: [:]), png.count <= Self.maxImageBytes {
            let fileName = id + ".png"
            guard write(png, to: Self.folder.appendingPathComponent(fileName)) else { return }
            item = ClipItem(id: id, kind: .image, text: "\(rep.pixelsWide) × \(rep.pixelsHigh)",
                            imageFile: fileName, date: Date())
        } else {
            return
        }
        deleteImages(of: history.add(item))
        deleteImages(of: history.prune(now: Date()))
        save()
    }

    /// 기록의 항목을 클립보드에 올리고, 맨 앞 앱에 붙여 넣는다 (⌘V 를 대신 눌러 준다).
    func paste(_ item: ClipItem) {
        guard copy(item) else { NSSound.beep(); return }
        // 런처가 닫히고 원래 앱이 다시 키 입력을 받을 시간을 준다
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.12) {
            let source = CGEventSource(stateID: .hidSystemState)
            for down in [true, false] {
                let event = CGEvent(keyboardEventSource: source, virtualKey: CGKeyCode(kVK_ANSI_V), keyDown: down)
                event?.flags = .maskCommand
                event?.post(tap: .cghidEventTap)
            }
        }
    }

    /// 항목을 클립보드에 올리기만 한다.
    @discardableResult
    func copy(_ item: ClipItem) -> Bool {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        var ok = false
        switch item.kind {
        case .text:
            ok = pasteboard.setString(item.text, forType: .string)
        case .file:
            let urls = item.text.split(separator: "\n").map { URL(fileURLWithPath: String($0)) as NSURL }
            ok = pasteboard.writeObjects(urls)
        case .image:
            if let file = item.imageFile,
               let data = try? Data(contentsOf: Self.folder.appendingPathComponent(file)) {
                ok = pasteboard.setData(data, forType: .png)
            }
        }
        // 방금 우리가 올린 것을 새 복사로 다시 기록하지 않는다
        changeCount = pasteboard.changeCount
        return ok
    }

    func imageURL(for item: ClipItem) -> URL? {
        item.imageFile.map { Self.folder.appendingPathComponent($0) }
    }

    func remove(_ item: ClipItem) {
        if let removed = history.remove(id: item.id) { deleteImages(of: [removed]) }
        save()
    }

    func clear() {
        deleteImages(of: history.clear())
        save()
    }

    // MARK: - 저장

    private func load() {
        guard let data = try? Data(contentsOf: Self.historyFile),
              let saved = try? JSONDecoder().decode(ClipHistory.self, from: data) else { return }
        history = saved
    }

    private func save() {
        guard let data = try? JSONEncoder().encode(history) else { return }
        _ = write(data, to: Self.historyFile)
    }

    /// 본인만 읽고 쓸 수 있게 저장한다.
    private func write(_ data: Data, to url: URL) -> Bool {
        let fm = FileManager.default
        do {
            try fm.createDirectory(at: Self.folder, withIntermediateDirectories: true, attributes: [.posixPermissions: 0o700])
            try data.write(to: url, options: .atomic)
            try fm.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
            return true
        } catch {
            NSLog("RisingKit: 클립보드 기록 저장 실패 (\(error.localizedDescription))")
            return false
        }
    }

    private func deleteImages(of items: [ClipItem]) {
        for item in items {
            if let url = imageURL(for: item) { try? FileManager.default.removeItem(at: url) }
        }
    }
}
